"""Render Q3 paper tables from existing inference outputs without rerunning models."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'outputs/q3_explanation/q3'
OUT = ROOT / 'paper/tables'
MODS = ['text', 'audio', 'vision']
CN = {'text': '文本', 'audio': '音频', 'vision': '视频'}

def number(x):
    if 0 < abs(x) < .00005:
        return f"${x:.0e}$".replace("e-06", r"\times10^{-6}")
    return f"{x:.4f}"


def escape(text):
    for a,b in [('&',r'\&'),('%',r'\%'),('_',r'\_'),('#',r'\#')]:
        text=text.replace(a,b)
    return text

def table(caption,label,columns,head,rows,ncols):
    return ('% Generated by src/q3_explanation/export_paper_tables.py\n'
            '\\begingroup\n\\setlength{\\tabcolsep}{3pt}\n'
            +r'\begin{longtable}{@{\extracolsep{\fill}}'+columns+'@{}}\n'
            +rf'\caption{{{caption}}}\label{{{label}}}\\'+'\n\\toprule\n'+head+'\n\\midrule\n\\endfirsthead\n'
            +rf'\multicolumn{{{ncols}}}{{c}}{{表 \thetable\ （续）}}\\'+'\n\\toprule\n'+head
            +'\n\\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n'
            +'\n'.join(' & '.join(row)+r' \\' for row in rows)
            +'\n\\end{longtable}\n\\endgroup\n')

def main():
    data=json.loads((DATA/'attachment4_explanations_full.json').read_text(encoding="utf-8"))
    assert len(data)==20 and len({r['sample_id'] for r in data})==20
    predictions=[];evidence=[]
    for r in data:
        shares=r['positive_share']
        assert abs(sum(shares)-1)<1e-6 or sum(shares)==0
        strength_main=MODS[max(range(3),key=lambda i:abs(r['shapley_strength_raw'][i]))]
        predictions.append([r['sample_id'],['负向','中性','正向'][r['polarity']],number(r['strength']),
                            number(r['full_probability']),CN[r['main_modality']],CN[strength_main],
                            *[f"{100*x:.2f}" for x in shares]])
        m=r['main_modality'];win=r['local'][m]['high']
        position=f"{win['start_position']}--{win['end_position']}"
        if m=='text':
            excerpt = r['evidence_transcript_words']
            # A window may capture an opening quote without its closing quote.
            # Normalize display punctuation only; preserve the source record.
            if excerpt.startswith('“') and '”' not in excerpt:
                excerpt = excerpt[1:]
            content=escape(excerpt)
        else:
            assert r['sample_id']=='05'
            content=(r'\raisebox{\dimexpr-.5\height+.5ex\relax}{\includegraphics[height=18mm]{../outputs/q3_explanation/q3/visual_candidate_05.png}}')
        times=r.get('evidence_time_seconds')
        interval=(f'[{times[0]:.3f}, {times[1]:.3f}]' if times else ('1.733' if r['sample_id']=='05' else '--'))
        evidence.append([r['sample_id'],CN[m],position,content,interval])
    OUT.mkdir(exist_ok=True)
    labels=['编号','极性','强度','预测概率',r'\makecell[c]{极性\\主模态}',r'\makecell[c]{强度\\主模态}']
    head=(' & '.join(r'\multirow{2}{*}{'+label+'}' for label in labels)
          +r' & \multicolumn{3}{c}{极性正贡献占比/\%} \\'+'\n'
          +r'\cmidrule(lr){7-9}'+'\n'+r' & & & & & & 文本 & 音频 & 视频 \\')
    (OUT/'附件四预测与贡献.tex').write_text(table('附件四全部样本的预测与模态贡献','tab:p3-attachment4','ccccccccc',head,predictions,9), encoding="utf-8")
    head=r'编号 & 模态 & 特征位置 & 关键原文或候选画面 & \mbox{时间区间或时刻/s} \\'
    (OUT/'附件四关键证据.tex').write_text(table('附件四全部样本的关键证据与对应位置','tab:p3-attachment4-evidence','cccC{76mm}c',head,evidence,5), encoding="utf-8")
    print('Exported 20 predictions and 20 evidence records')

if __name__=='__main__':
    main()
